    func detailPath(in r: CGRect) -> CGPath? { detail.isEmpty ? nil : Self.build(detail, in: r) }
    func bodyRect(in r: CGRect) -> CGRect {
        CGRect(x: r.minX + r.width * body.minX / 100, y: r.minY + r.height * body.minY / 100,
